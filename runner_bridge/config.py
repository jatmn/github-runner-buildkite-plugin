import hashlib
import json
import re
from dataclasses import asdict, dataclass, fields

from .api import BridgeError

REPO = re.compile(r"[A-Za-z0-9_.-]+/[A-Za-z0-9_.-]+\Z")
SLUG = re.compile(r"[A-Za-z0-9][A-Za-z0-9_-]*\Z")


@dataclass
class Config:
    repository: str
    queue: str
    plugin: str
    app_id: str = ""
    installation_id: str = ""
    key_secret: str = "RUNNER_BRIDGE_APP_KEY"
    label: str = "buildkite-pullfrog"
    workflow: str = ".github/workflows/pullfrog.yml"
    branch: str = "main"
    image: str = "bundled"
    startup_seconds: int = 300
    execution_seconds: int = 3900
    relax_container_sandbox: bool = False

    def validate(self):
        if not REPO.fullmatch(self.repository) or any(p in (".", "..") for p in self.repository.split("/")):
            raise BridgeError("Repository must be OWNER/REPO")
        for value in (self.queue, self.label, self.key_secret):
            if not SLUG.fullmatch(value):
                raise BridgeError("Queue, label and secret name must contain only letters, digits, underscores or hyphens")
        if not re.fullmatch(r"[A-Za-z0-9_.-]+/github-runner#[0-9a-f]{40}", self.plugin):
            raise BridgeError("Plugin must be OWNER/github-runner#FULL_COMMIT_SHA")
        if not re.fullmatch(r"\.github/workflows/[A-Za-z0-9_.-]+\.ya?ml", self.workflow):
            raise BridgeError("Invalid workflow path")
        if self.image != "bundled" and not re.fullmatch(r"[A-Za-z0-9._:/-]+@sha256:[0-9a-f]{64}", self.image):
            raise BridgeError("Custom runner image must be pinned by sha256 digest")
        if not self.branch or self.branch.startswith("-") or any(c.isspace() for c in self.branch):
            raise BridgeError("Invalid trusted default branch")
        if not 30 <= int(self.startup_seconds) <= 3600 or not 60 <= int(self.execution_seconds) <= 21600:
            raise BridgeError("Invalid runner timeout")
        if not isinstance(self.relax_container_sandbox, bool):
            raise BridgeError("relax_container_sandbox must be a boolean")
        for identifier in (self.app_id, self.installation_id):
            if identifier and not str(identifier).isdigit():
                raise BridgeError("App and installation IDs must be numeric")
        return self

    def data(self):
        return asdict(self)

    @classmethod
    def load(cls, data):
        if isinstance(data, str):
            data = json.loads(data)
        known = {f.name for f in fields(cls)}
        if not isinstance(data, dict) or set(data) - known:
            raise BridgeError("Unknown configuration fields")
        return cls(**data).validate()


def identity(repository, job):
    raw = f"{repository.lower()}:{int(job['id'])}:{int(job['run_attempt'])}"
    return hashlib.sha256(raw.encode()).hexdigest()[:32]


def run_label(job):
    return f"pullfrog-{int(job['run_id'])}-{int(job['run_attempt'])}"


def step(config, mode, job=None):
    options = {"config": json.dumps(config.data()), "mode": mode}
    result = {"label": f"GitHub runner bridge: {mode}", "agents": {"queue": config.queue},
              "plugins": [{config.plugin: options}], "timeout_in_minutes": 10}
    if job:
        options["job-id"] = int(job["id"])
        key = identity(config.repository, job)
        result.update({"key": "runner-" + key, "concurrency": 1,
                       "concurrency_group": "github-runner-bridge/" + key,
                       "timeout_in_minutes": (config.startup_seconds + config.execution_seconds) // 60 + 5,
                       "retry": {"automatic": [{"exit_status": 75, "limit": 2}]}})
    return result


def pipeline(config):
    # JSON is valid YAML. No local repository checkout is required by the hooks.
    return json.dumps({"steps": [step(config, "dispatch")]}, indent=2)


def pullfrog_workflow(config, pullfrog_sha, checkout_sha):
    for sha in (pullfrog_sha, checkout_sha):
        if not re.fullmatch(r"[0-9a-f]{40}", sha):
            raise BridgeError("Actions must be pinned to full commit SHAs")
    return f'''# Generated by buildkite-runner-bridge. Pullfrog uses its normal dispatch trigger.
name: Pullfrog
run-name: ${{{{ inputs.name || github.workflow }}}}
on:
  workflow_dispatch:
    inputs:
      prompt:
        type: string
      name:
        type: string
permissions:
  contents: read
jobs:
  pullfrog:
    runs-on:
      - {config.label}
      - "pullfrog-${{{{ github.run_id }}}}-${{{{ github.run_attempt }}}}"
    timeout-minutes: {max(1, config.execution_seconds // 60 - 1)}
    permissions:
      contents: read
      id-token: write
    steps:
      - uses: actions/checkout@{checkout_sha}
        with:
          ref: ${{{{ github.event.repository.default_branch }}}}
          persist-credentials: false
      - uses: pullfrog/pullfrog@{pullfrog_sha}
        with:
          prompt: ${{{{ inputs.prompt }}}}
          push: disabled
          shell: restricted
'''
